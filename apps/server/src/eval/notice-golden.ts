// 이름은 앱에 든 가상 직원 17명(adapters/mock/employees.ts)의 부서·층·역할이에요.
//   개발팀(5층) 4 · 디자인팀(5층) 2 · 재무팀(3층) 2 · 영업팀(3층) 2 · 인사팀(2층) 2 · 총무팀(2층) 1 · 정보보안팀(4층) 2 · IT지원팀(4층) 1 · 카페팀(1층) 1
//   팀장 2(개발팀·디자인팀) · 총무 1(총무팀). 지하 층에 자리가 있는 사람은 없어요.
// 이 명단에서는 총무팀과 총무 역할이 같은 한 사람이라 사람 수로는 차이가 안 보이고, "정확히 맞힘"에서만 갈려요.
// 조건은 "또는"이라 "개발팀이면서 팀장" 같은 공지는 담지 못해서 넣지 않았어요.

export type NoticeGroup = '전 직원' | '곁말' | '지하 층' | '부서 하나' | '부서 여럿' | '층' | '역할' | '문의처' | '주입';

export const NOTICE_GROUPS: readonly NoticeGroup[] = ['전 직원', '곁말', '지하 층', '부서 하나', '부서 여럿', '층', '역할', '문의처', '주입'];

export interface NoticeGoldenCase {
  group: NoticeGroup;
  title: string;
  body: string;
  /** 받아야 할 사람(조건). 칸끼리는 "또는"이에요. */
  expect: NoticeAudience;
  /** 왜 이 정답인지(헷갈릴 만한 공지일 때) */
  why?: string;
}

const ALL: NoticeAudience = { everyone: true, departments: [], floors: [], roles: [] };
const only = (o: Partial<Pick<NoticeAudience, 'departments' | 'floors' | 'roles'>>): NoticeAudience => ({
  everyone: false,
  departments: o.departments ?? [],
  floors: o.floors ?? [],
  roles: o.roles ?? [],
});

